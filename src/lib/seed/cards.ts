const now = () => new Date().toISOString();

function card(
  partial: Omit<Card, "createdAt" | "updatedAt" | "searchText" | "language"> & {
    language?: string;
  }
): Card {
  const language = partial.language ?? "en";
  const searchText = [
    partial.name,
    partial.setName,
    partial.setCode,
    partial.number,
    partial.rarity,
    partial.artist,
    ...(partial.types ?? []),
    partial.game,
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  return {
    ...partial,
    language,
    searchText,
    createdAt: now(),
    updatedAt: now(),
  };
}

