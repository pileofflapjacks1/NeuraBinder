const DEMO_USER = "demo-user";

function uc(
  partial: Omit<UserCard, "userId" | "createdAt" | "updatedAt" | "listIds"> & {
    listIds?: string[];
  }
): UserCard {
  const cardData = SEED_CARDS.find((c) => c.id === partial.cardId);
  const estimatedValue = estimateUnitValue(
    cardData?.marketPrice,
    partial.condition,
    partial.isGraded,
    partial.gradeCompany,
    partial.grade
  );
  return {
    ...partial,
    userId: DEMO_USER,
    listIds: partial.listIds ?? ["list-collection"],
    estimatedValue,
    createdAt: now(),
    updatedAt: now(),
  };
}

